"""Write the meshDict schema (cutmesh/schema.py) for the documentation site:

    docs/meshdict.schema.json   the JSON Schema (for editors: "$schema" in a meshDict)
    docs/meshdict-data.js       the same and the meshDicts of examples/, as a script for
                                docs/meshdict.html (so that it also works opened as a file)

Both files are generated in docs/ (Japanese) and docs/en/ (English).

    python tools/gen_meshdict_schema.py          # write both languages
    python tools/gen_meshdict_schema.py --check  # exit 1 when any copy is out of date

tests/test_schema.py runs the check, so edit cutmesh/schema.py and run this after a change.
"""
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from cutmesh.schema import schema_json  # noqa: E402

DOCS = os.path.join(ROOT, "docs")


def examples():
    """{"stirred_tank/meshDict.json": {...}, ...}: the example meshDicts, in name order"""
    out = {}
    for path in sorted(glob.glob(os.path.join(ROOT, "examples", "*", "meshDict*.json"))):
        with open(path, encoding="utf-8-sig") as f:
            out[os.path.relpath(path, os.path.join(ROOT, "examples")).replace(os.sep, "/")] = json.load(f)
    return out


def outputs():
    ex = json.dumps(examples(), ensure_ascii=False, indent=1)
    files = {}
    for language, directory in (("ja", DOCS), ("en", os.path.join(DOCS, "en"))):
        s = schema_json(language=language)
        files[os.path.join(directory, "meshdict.schema.json")] = s
        files[os.path.join(directory, "meshdict-data.js")] = (
            "// generated by tools/gen_meshdict_schema.py from cutmesh/schema.py and examples/: do not edit\n"
            "window.MESHDICT_SCHEMA = " + s.rstrip("\n") + ";\n"
            "window.MESHDICT_EXAMPLES = " + ex + ";\n"
        )
    return files


def stale():
    out = []
    for path, text in outputs().items():
        try:
            with open(path, encoding="utf-8", newline="") as f:
                same = f.read().replace("\r\n", "\n") == text   # a CRLF checkout (autocrlf) is the same
        except FileNotFoundError:
            same = False
        if not same:
            out.append(path)
    return out


def main(argv):
    if "--check" in argv:
        bad = stale()
        for p in bad:
            print(f"out of date: {os.path.relpath(p, ROOT)} (run python tools/gen_meshdict_schema.py)")
        return 1 if bad else 0
    for path, text in outputs().items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(path, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
